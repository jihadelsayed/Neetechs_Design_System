/**
 * Writes src/version.ts from package.json so the runtime NEETECHS_UI_VERSION
 * can never drift from the published version. Runs before every build, and
 * semantic-release's `npm publish` triggers `prepack` → build after it bumps
 * package.json, so the tarball always carries the released version.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url);
const { version } = JSON.parse(readFileSync(new URL('package.json', root), 'utf8'));
const target = new URL('src/version.ts', root);
const contents = `// Generated by scripts/sync-version.mjs from package.json. Do not edit.\nexport const NEETECHS_UI_VERSION = '${version}';\n`;

let current = '';
try {
  current = readFileSync(target, 'utf8');
} catch {
  current = '';
}

if (current !== contents) {
  writeFileSync(target, contents);
}
